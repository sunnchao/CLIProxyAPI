func TestOpenAICompatExecutorResponsesFallbacksToChatCompletionsWhenDisabled(t *testing.T) {
	var gotPath string
	var gotBody []byte
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotPath = r.URL.Path
		body, _ := io.ReadAll(r.Body)
		gotBody = body
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(`{"id":"chatcmpl-1","object":"chat.completion","choices":[{"index":0,"message":{"role":"assistant","content":"hello"},"finish_reason":"stop"}],"usage":{"prompt_tokens":1,"completion_tokens":2,"total_tokens":3}}`))
	}))
	defer server.Close()

	executor := NewOpenAICompatExecutor("openai-compatibility", &config.Config{
		OpenAICompatibility: []config.OpenAICompatibility{
			{
				Name:    "pool",
				BaseURL: server.URL + "/v1",
			},
		},
	})
	auth := &cliproxyauth.Auth{
		Provider: "pool",
		Attributes: map[string]string{
			"base_url":     server.URL + "/v1",
			"api_key":      "test",
			"compat_name":  "pool",
			"provider_key": "pool",
		},
	}
	payload := []byte(`{"model":"gpt-5.1-codex-max","input":[{"role":"user","content":"hi"}]}`)
	if _, err := executor.Execute(context.Background(), auth, cliproxyexecutor.Request{
		Model:   "gpt-5.1-codex-max",
		Payload: payload,
	}, cliproxyexecutor.Options{
		SourceFormat: sdktranslator.FromString("openai-response"),
		Stream:       false,
	}); err != nil {
		t.Fatalf("Execute error: %v", err)
	}
	if gotPath != "/v1/chat/completions" {
		t.Fatalf("path = %q, want %q", gotPath, "/v1/chat/completions")
	}
	if len(gotBody) == 0 {
		t.Fatal("expected translated request body")
	}
}

func TestOpenAICompatExecutorResolveCompatConfig_SkipsDisabled(t *testing.T) {
	disabled := false
	executor := NewOpenAICompatExecutor("openai-compatibility", &config.Config{
		OpenAICompatibility: []config.OpenAICompatibility{
			{
				Name:    "pool",
				Enabled: &disabled,
				BaseURL: "https://disabled.example.com/v1",
			},
		},
	})
	auth := &cliproxyauth.Auth{
		Provider: "pool",
		Attributes: map[string]string{
			"compat_name":  "pool",
			"provider_key": "pool",
		},
	}

	if got := executor.resolveCompatConfig(auth); got != nil {
		t.Fatalf("expected disabled provider to be ignored, got %+v", got)
	}
}
